# PlatformIO pre-build script: writes src/build_stamp.h with a hash of the
# firmware source, so the chair can tell a NEW firmware from an ordinary power-on
# (it chases its LEDs once after an upload). Same source -> same stamp -> same hex.
import hashlib, os
Import("env")  # noqa: F821 (provided by PlatformIO)
src = os.path.join(env["PROJECT_DIR"], "src")  # noqa: F821
h = hashlib.sha1()
for root, dirs, files in sorted(os.walk(src)):
    dirs.sort()
    for f in sorted(files):
        if f == "build_stamp.h" or not f.endswith((".h", ".cpp", ".c")):
            continue
        p = os.path.join(root, f)
        h.update(os.path.relpath(p, src).encode()); h.update(open(p, "rb").read())
stamp = int(h.hexdigest()[:8], 16)
text = ("#pragma once\n// Generated by tools/build_stamp.py: hash of src/. Not committed.\n"
        "#define BUILD_STAMP 0x%08xUL\n" % stamp)
out = os.path.join(src, "build_stamp.h")
if not os.path.exists(out) or open(out).read() != text:
    open(out, "w").write(text)
