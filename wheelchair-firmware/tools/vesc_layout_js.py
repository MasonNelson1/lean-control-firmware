"""Generate debugViewer/vesc-conf-layout.js from tools/vesc/confgenerator_6_06.c.

The dashboard decodes the DBG VCONF dumps (COMM_GET_MCCONF / COMM_GET_APPCONF
replies) with this field order, the same one tools/vesc_conf.py uses.

    python3 tools/vesc_layout_js.py            # rewrite the file
    python3 tools/vesc_layout_js.py --check    # exit 1 if it is out of date
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import vesc_conf  # noqa: E402

OUT = os.path.join(HERE, "..", "debugViewer", "vesc-conf-layout.js")
SIZE = {"u8": 1, "uint16": 2, "int16": 2, "uint32": 4, "int32": 4, "float16": 2, "float32": 4, "float32_auto": 4}


def render():
    layout = {}
    for kind, cmd in (("mcconf", 14), ("appconf", 17)):
        fields = vesc_conf.layout(kind)
        # The signature (uint32) is the first field of both configs.
        layout[kind] = {"command": cmd, "signature": vesc_conf.SIG[kind],
                        "bytes": sum(SIZE[t] for _, t, _ in fields),
                        "fields": [[name, t, scale] for name, t, scale in fields]}
    body = json.dumps(layout, separators=(",", ":"))
    return ("'use strict';\n"
            "// Generated by tools/vesc_layout_js.py from tools/vesc/confgenerator_6_06.c (VESC firmware 6.06).\n"
            "// Do not edit. Field = [name, type, scale]; read-only use: the dashboard only shows VESC settings.\n"
            f"const VescConfLayout = Object.freeze({body});\n")


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        current = open(OUT).read() if os.path.exists(OUT) else ""
        sys.exit(0 if current == text else 1)
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT)}")
